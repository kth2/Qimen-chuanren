  const MATCHERS = [];
  for (const t of TERMS) for (const m of t.match) MATCHERS.push({ m, id: t.id });
  MATCHERS.sort((a, b) => b.m.length - a.m.length);
  const BY_ID = Object.fromEntries(TERMS.map((t) => [t.id, t]));
  // 单字的刑、冲、破、害太常见，只在它们紧跟「用」「时为日」或作「X为」时才认
  const SINGLE = new Set(['刑', '冲', '破', '害']);

  /** 句子里出现哪些卡（每卡一次，按出现先后） */
  function find(text) {
    const s = String(text || ''), hits = [];
    const seen = new Set();
    for (const { m, id } of MATCHERS) {
      if (seen.has(id)) continue;
      const i = s.indexOf(m);
      if (i < 0) continue;
      if (SINGLE.has(m) && !/[用为日见临加带]$/.test(s.slice(Math.max(0, i - 1), i)) && !/[、：]/.test(s[i + 1] || '')) continue;
      seen.add(id); hits.push({ id, at: i, len: m.length });
    }
    return hits.sort((a, b) => a.at - b.at);
  }

